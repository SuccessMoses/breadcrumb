const pick = (): string => {
  const [value] = crypto.getRandomValues(new Uint32Array(1));
  return WORDS[(value ?? 0) % WORDS.length] ?? "sequence";
};

// A word not already used by another sequence; a number is added if they all are
export const randomName = (taken: ReadonlySet<string>): string => {
  for (let attempt = 0; attempt < 50; attempt++) {
    const name = pick();
    if (!taken.has(name)) return name;
  }
  const base = pick();
  let n = 2;
  while (taken.has(`${base}${n}`)) n++;
  return `${base}${n}`;
};
